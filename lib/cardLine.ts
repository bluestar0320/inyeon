/** 구간 머리: steps 중 n 이하인 가장 큰 값. 없으면 null. */
function stepOf(n: number, steps: number[]): number | null {
  let hit: number | null = null;
  for (const s of steps) if (n >= s) hit = s;
  return hit;
}

function hash(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 16777619);
  return h >>> 0;
}

function groupOf(rel: Rel): Group {
  return rel === "parent" || rel === "grandparent" ? "family" : rel === "partner" || rel === "child" ? rel : "friend";
}

export function cardLine(i: {
  /** 함께한 횟수 */
  past: number;
  /** 알고 지낸 햇수. 모르면 null */
  years: number | null;
  rel: Rel;
  /** 사람마다 고정되게 고르는 열쇠(사람 id) */
  seed: string;
  lang: Lang;
  /** 비율 문장(bondBand). 다른 언어는 이것만 쓴다 */
  bond?: string;
}): string | undefined {
  const pick = (lines: string[], key: string) => lines[hash(`${i.seed}:${key}`) % lines.length];
  // 이스터 에그는 그 숫자 딱 하나에서만.
  const egg = String(Math.round(i.past));
  if (egg in EGG) return pick(EGG[egg as keyof typeof EGG][i.lang], egg);
  if (i.lang !== "ko") return i.bond;
  const pool: string[] = [];
  const c = stepOf(i.past, Object.keys(COUNT).map(Number));
  if (c !== null) pool.push(...COUNT[c]);
  const table = YEARS[groupOf(i.rel)];
  const y = i.years === null ? null : stepOf(i.years, Object.keys(table).map(Number));
  if (y !== null) pool.push(...table[y]);
  if (i.bond) pool.push(i.bond);
  return pool.length ? pick(pool, `${c}:${y}`) : undefined;
}

/** 알고 지낸 햇수: 「언제부터」가 있으면 그때부터, 없으면 부모님·조부모님은 내 나이, 자녀는 그 아이 나이. */
export function yearsKnown(i: { rel: Rel; since?: string; myAge: number | null; theirAge: number | null; now?: Date }): number | null {
  if (i.since) {
    const start = new Date(`${i.since}T00:00:00`);
    if (Number.isNaN(start.getTime())) return null;
    const years = ((i.now ?? new Date()).getTime() - start.getTime()) / 31_557_600_000;
    return years >= 0 ? Math.floor(years) : null;
  }
  if (i.rel === "parent" || i.rel === "grandparent") return i.myAge;
  if (i.rel === "child") return i.theirAge;
  return null;
}
